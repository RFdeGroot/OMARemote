#!/usr/bin/env python3
"""gen_nerd_font.py <nerd_font_tables.zig> <out.hpp>: Ghostty's Nerd Font glyph constraints
(src/font/nerd_font_tables.zig in the pinned libghostty-vt source, MIT, itself generated from the
Nerd Fonts patcher) as a C++ header for omaremote-ssh: how each icon is sized and placed in its
cell(s). The same three-stage lookup: stage3[stage2[stage1[cp >> 8] + (cp & 0xff)]], entry 0 none.
"""
import re
import sys

SIZES = ["none", "fit", "cover", "fit_cover1", "stretch"]
ALIGNS = ["none", "start", "end", "center", "center1"]
HEIGHTS = ["cell", "icon"]
NUMBERS = ["pad_top", "pad_left", "pad_right", "pad_bottom",
           "relative_width", "relative_height", "relative_x", "relative_y", "max_xy_ratio"]
DEFAULTS = {"relative_width": 1.0, "relative_height": 1.0}


def numbers(text, name):
    m = re.search(rf"pub const {name}: \[(\d+)\]u16 = \.\{{([^}}]*)\}};", text)
    if not m:
        sys.exit(f"gen_nerd_font: no {name} in the table")
    values = [int(v) for v in m.group(2).replace("\n", " ").split(",") if v.strip()]
    if len(values) != int(m.group(1)):
        sys.exit(f"gen_nerd_font: {name} has {len(values)} values, not {m.group(1)}")
    return values


def entries(text):
    m = re.search(r"pub const stage3: \[(\d+)\]Elem = \.\{(.*)\n\s*\};", text, re.S)
    if not m:
        sys.exit("gen_nerd_font: no stage3 in the table")
    body, out, depth, start = m.group(2), [], 0, None
    # Top-level items: `null` or `.{ ... }` (no nesting inside a constraint).
    i = 0
    while i < len(body):
        if body.startswith("null", i) and depth == 0:
            out.append(None)
            i += 4
            continue
        if body.startswith(".{", i):
            depth, start = 1, i + 2
            i += 2
            continue
        if body[i] == "}" and depth:
            out.append(body[start:i])
            depth = 0
        i += 1
    if len(out) != int(m.group(1)):
        sys.exit(f"gen_nerd_font: stage3 has {len(out)} entries, not {m.group(1)}")
    return out


def constraint(fields):
    if fields is None:
        return "{}"
    seen = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n]+)", fields))
    known = {"size", "align_vertical", "align_horizontal", "height", "max_constraint_width", *NUMBERS}
    if set(seen) - known:
        sys.exit(f"gen_nerd_font: unknown fields {sorted(set(seen) - known)}")

    def enum(name, values):
        v = seen.get(name, ".none" if name != "height" else ".cell").strip().lstrip(".")
        if v not in values:
            sys.exit(f"gen_nerd_font: {name} = {v}?")
        return str(values.index(v))

    nums = []
    for name in NUMBERS:
        v = float(seen[name]) if name in seen else DEFAULTS.get(name, 0.0)
        nums.append(repr(v))
    width = int(seen.get("max_constraint_width", "2"))
    return ("{true, " + enum("size", SIZES) + ", " + enum("align_vertical", ALIGNS) + ", "
            + enum("align_horizontal", ALIGNS) + ", " + enum("height", HEIGHTS) + ", " + str(width) + ", "
            + ", ".join(nums) + "}")


def main():
    src, out = sys.argv[1:3]
    text = open(src, encoding="utf-8").read()
    stage1, stage2, stage3 = numbers(text, "stage1"), numbers(text, "stage2"), entries(text)
    if stage3[0] is not None or len(stage1) != 0x2000 or max(stage2) >= len(stage3) \
            or max(stage1) + 256 > len(stage2):
        sys.exit("gen_nerd_font: the table is not laid out as expected")
    rows = lambda vs: ",\n".join("\t" + ", ".join(map(str, vs[i:i + 32])) for i in range(0, len(vs), 32))
    with open(out, "w", encoding="utf-8") as f:
        f.write("// Generated by native/ghostty-vt/gen_nerd_font.py from Ghostty's nerd_font_tables.zig (MIT).\n"
                "// Do not edit: it follows the pinned libghostty-vt version.\n#pragma once\n#include <cstdint>\n\n"
                "namespace nerdfont {\n\n"
                "enum Size : uint8_t { None, Fit, Cover, FitCover1, Stretch };\n"
                "enum Align : uint8_t { AlignNone, Start, End, Center, Center1 };\n"
                "enum Height : uint8_t { CellHeight, IconHeight };\n\n"
                "struct Constraint\n{\n\tbool known = false;\n\tuint8_t size = None, alignV = AlignNone, alignH = AlignNone;\n"
                "\tuint8_t height = CellHeight, maxWidth = 2;\n"
                "\tdouble padTop = 0, padLeft = 0, padRight = 0, padBottom = 0;\n"
                "\tdouble relWidth = 1, relHeight = 1, relX = 0, relY = 0;\n"
                "\tdouble maxXYRatio = 0; // 0: none\n};\n\n")
        f.write(f"inline constexpr uint16_t kStage1[{len(stage1)}] = {{\n{rows(stage1)}}};\n\n")
        f.write(f"inline constexpr uint16_t kStage2[{len(stage2)}] = {{\n{rows(stage2)}}};\n\n")
        f.write(f"inline constexpr Constraint kStage3[{len(stage3)}] = {{\n"
                + ",\n".join("\t" + constraint(e) for e in stage3) + "};\n\n")
        f.write("// The constraint for cp; .known is false when it has none.\n"
                "inline const Constraint& get(uint32_t cp)\n{\n"
                "\tstatic const Constraint none;\n"
                "\tif (cp > 0x1FFFFF)\n\t\treturn none;\n"
                "\treturn kStage3[kStage2[kStage1[cp >> 8] + (cp & 0xFF)]];\n}\n\n"
                "} // namespace nerdfont\n")


if __name__ == "__main__":
    main()
